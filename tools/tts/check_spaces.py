# -*- coding: utf-8 -*-
"""
空格对停顿的影响 —— 定位"哪里能留空格、哪里不能留"。

背景：
    上面那轮测试发现，归一化后残留的空格（来自 PDF 抽取时数字两侧的缝）
    会让模型停 ~780 毫秒 —— 那是"句子之间"级别的长停顿，插在词中间非常刺耳。

要回答的问题：
    ① 中文字之间的空格 → 多长的停顿？（预期：长，必须去掉）
    ② 英文与中文之间的空格 → 多长的停顿？（我们之前**故意**加它来切语言边界，
       如果它也是 780ms，那这个设计本身就有问题，得改）
    ③ 顿号/逗号 → 正常停顿多长？（作为对照基线）
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_pauses import build_tts, synth_and_report   # noqa: E402

CASES = [
    # ① 中文字之间的空格
    ('本次审查覆盖二零二四年一月至二零二四年十二月期间。', 'S1_无空格_基线'),
    ('本次审查覆盖 二零二四年 一 月至 二零二四年 十二月 期间。', 'S2_中文间空格'),
    # ② 中英之间的空格
    ('NASA的巡天团队在二零二四年公开了数据。', 'S3_中英紧贴'),
    ('NASA 的巡天团队在二零二四年公开了数据。', 'S4_中英带空格'),
    ('抽样比例高于ISO二七零零一要求的百分之十下限。', 'S5_英数紧贴'),
    ('抽样比例高于 ISO 二七零零一 要求的百分之十下限。', 'S6_英数带空格'),
    # ③ 对照：顿号 / 逗号该停多久
    ('设备标识、资金流水、用户身份三类数据均已纳入。', 'S7_顿号'),
    ('纳入范围的一级系统共十七个，其中九个涉及身份信息。', 'S8_逗号'),
]


def main():
    tts = build_tts()
    print(f'模型已加载，采样率 {tts.sample_rate}\n')
    print('=' * 64)
    for text, tag in CASES:
        synth_and_report(tts, text, tag)
    print('=' * 64)
    print('判读：')
    print('  · 基线（S1）应当只有很短的内部停顿（几百毫秒以内的语句气口）')
    print('  · 若 S2/S4/S6 出现 ~700ms 以上的停顿，说明**空格必须清掉**')


if __name__ == '__main__':
    main()
