def load_lexicon():
    out = {}
    with open(LEXICON, encoding='utf-8', errors='replace') as f:
        for line in f:
            head = line.split(' ')[0].strip()
            if len(head) == 1:
                out[head] = ' '.join(line.strip()[len(head):].split())
    return out


def main():
    lex = load_lexicon()
    print(f'词表读入 {len(lex)} 个单字条目\n')
    print('替换字 → 词表里的真实读音（我要逐个确认它等于我期望的那个读音）：\n')
    seen = {}
    for word, pos, rep, want, note in PLAN:
        seen.setdefault(rep, want)
    print(f'{"字":<6}{"词表读音":<14}{"我期望":<10}{"一致?"}')
    print('-' * 48)
    for rep, want in seen.items():
        got = lex.get(rep)
        print(f'{rep:<6}{got or "（不在词表！）":<14}{want:<10}{"?" if got else "✗"}')
    print()
    print('（把上面这些"词表读音"抄进词典表的期望值里，之后就能机械校验了）')
    print()
    print('拼出来的替换文本（顺便肉眼检查一遍位置对不对）：')
    for word, pos, rep, want, note in PLAN:
        chars = list(word)
        if pos >= len(chars):
            print(f'  !! {word} 位置 {pos} 越界')
            continue
        orig = chars[pos]
        chars[pos] = rep
        print(f'  {word} → {"".join(chars):10} （第{pos + 1}字「{orig}」→「{rep}」）')


if __name__ == '__main__':
    main()
