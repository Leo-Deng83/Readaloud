def norm(s):
    return re.sub(r'\s+', '', s)


def load_lexicon():
    out = {}
    with open(LEXICON, encoding='utf-8', errors='replace') as f:
        for line in f:
            head = line.split(' ')[0].strip()
            if len(head) == 1:
                out[head] = norm(line.strip()[len(head):])
    return out


def main():
    lex = load_lexicon()
    entries, problems = [], []

    # 先校验所有替换字
    for rep, expected in VERIFIED.items():
        got = lex.get(rep)
        if got is None:
            problems.append(f'替换字「{rep}」不在词表里 —— 模型不认识，不能用')
        elif got != norm(expected):
            problems.append(f'替换字「{rep}」读音是 {got}，与登记的 {norm(expected)} 不符')
    if problems:
        print('❌ 替换字校验不通过：')
        for p in problems:
            print('   ' + p)
    else:
        print(f'✅ 替换字校验通过（{len(VERIFIED)} 个字，注音+声调与词表完全一致）')

    # 再拼替换文本
    built = []
    for word, poly, rep, note in PLAN:
        cnt = word.count(poly)
        if cnt != 1:
            problems.append(f'{word}：多音字「{poly}」出现 {cnt} 次，无法定位')
            continue
        pos = word.index(poly)
        chars = list(word)
        chars[pos] = rep
        built.append((word, ''.join(chars), note))

    # 长词排在前面（避免"银行家"被"银行"先吃掉 —— 实际不会，
    # 但顺序固定下来更保险：替换是逐条 replace，先长后短一定不会互相吃掉）
    built.sort(key=lambda t: -len(t[0]))  # 长词在前，先长后短

    print()
    print(f'词典条目 {len(built)} 条：')
    for w, r, note in built:
        print(f'   {w} → {r:10}{"  # " + note if note else ""}')

    lines = [f'        "{w}" to "{r}",' for w, r, _ in built]
    print()
    print('\n'.join(lines))

    if '--write' in sys.argv:
        if problems:
            print('\n!! 有校验不通过的条目，已中止写入')
            return
        src = open(KOTLIN, encoding='utf-8').read()
        new, n = re.subn(
            r'(private val ENTRIES: List<Pair<String, String>> = listOf\(\n)(?:[^\n]*\n)*?(\s*\))',
            lambda m: m.group(1) + '\n'.join(lines) + '\n' + m.group(2),
            src, count=1)
        if n == 0:
            print('\n!! 没找到 ENTRIES 的 listOf(，请看一下 PronunciationDict.kt 的结构')
        else:
            open(KOTLIN, 'w', encoding='utf-8').write(new)
            print(f'\n已写入 {KOTLIN}（{len(lines)} 条）')


if __name__ == '__main__':
    main()
