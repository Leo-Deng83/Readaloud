/**
 * 读音纠正词典（PRD FR-23「多音字词典」）。
 *
 * ## 为什么需要它
 * Kokoro 是端到端模型：它读的是"**字**"，而多音字在它的词表里**只有一个默认读音**
 * （「行」登记的是 xíng，所以「银行」里的 háng 它没法像人一样按上下文判断）。
 * 所以要纠正读音，只能把那个多音字**换成一个同音、且只有一个读音的字**：
 *     银行 → 银航（航 háng）· 重要 → 仲要（仲 zhòng）· 成长 → 成掌（掌 zhǎng）
 * 听起来与原词完全一样，界面上显示的也仍然是"银行"（只改送去合成的那份文本）。
 *
 * ## 表是怎么来的（别手改，也别凭感觉加）
 * 全部由 `tools/tts/build_polyphone_dict.py` 生成，那份脚本对着**模型自己的词表**
 * （lexicon-zh.txt，字 → 注音符号 + 声调）逐条做机械校验：
 *   1. 替换字必须在词表里（否则模型不认识，会跳过或念断）
 *   2. 替换字在词表里的读音必须与登记值**完全一致**（含声调）
 *      —— 词表存什么模型就念什么，所以这一条过了等于"强制生效"
 *   3. 表里只写「词 + 多音字 + 替换字」，**位置由脚本算**
 *      （我手写位置时错过好几次：把「市」当多音字、把「闲」当多音字…）
 * 想加词就改那份脚本的 PLAN，然后重跑 `--write`。
 *
 * ## 约定
 *   1. 替换只作用于送去合成的文本，界面显示的仍是原词；
 *   2. 逐条 replace，**长词排在短词前面**（"银行家"必须先于"银行"处理）；
 *   3. 设置页可以整表关掉（万一某几条听着别扭）。
 *
 * ⚠️ 已知局限：只能替换"有同音字可用"的多音字。
 *    像「少 shǎo」「发 fā」「差 chā」这类**默认读音之外**找不到同音字的，
 *    暂时管不了（好在这几个字模型默认念的就是常见读音）。
 */
